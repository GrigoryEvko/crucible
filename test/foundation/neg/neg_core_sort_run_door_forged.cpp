// A unit that is not the stable sort or the radix sort, such as a door of
// another owner of the base or a file of src/, calls the door of the sort to
// make a View of any pointer and any count.  StableSort and radix_sort_ are
// the friends of the door, so its member is private here.

#include <foundation/core/Sort.h>

int main() {
    using Count = foundation::core::Quantity<foundation::core::unit::Element, std::size_t>;
    static_cast<void>(foundation::core::SortRunDoor::run_(static_cast<int*>(nullptr), Count{4}));
    return 0;
}
