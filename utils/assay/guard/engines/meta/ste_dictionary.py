def suffix_bases(word: str) -> list[tuple[str, bool]]:
    """Return each word that the removal of one suffix gives, with True when the suffix is a suffix of a verb only."""
    bases: list[tuple[str, bool]] = [(word[:-3] + "y", False)] if word.endswith("ies") else []
    bases += [(word[:-2], False)] if word.endswith("es") else []
    bases += [(word[:-1], False)] if word.endswith("s") and not word.endswith("ss") else []
    bases += [(word[:-3] + "y", True)] if word.endswith("ied") else []
    if word.endswith("ed"):
        bases += [(word[:-2], True), (word[:-1], True)]
        bases += [(word[:-3], True)] if len(word) > 4 and word[-3] == word[-4] else []
    if word.endswith("ing"):
        bases += [(word[:-3], True), (word[:-3] + "e", True)]
        bases += [(word[:-4], True)] if len(word) > 5 and word[-4] == word[-5] else []
    return bases


def refused_base(word: str, exempt: frozenset[str]) -> str | None:
    """Return the word of REFUSED that a lowercase word of a text is a shape of, or None (THE SHAPES OF A WORD).

    A word of `exempt`, the words of the term rows, gives None for each of its shapes.
    """
    if word in CONFUSABLE:
        return None
    if word in REFUSED:
        return None if word in exempt else word
    for base, is_verb_suffix in suffix_bases(word):
        entry = REFUSED.get(base)
        if entry is None or base in exempt:
            continue
        if not is_verb_suffix or VERB in entry[0].split():
            return base
    return None
